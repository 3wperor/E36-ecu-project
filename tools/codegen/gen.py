#!/usr/bin/env python3
"""
Generate firmware headers, the TunerStudio .ini and the tool definition JSON
from definitions/ecu.toml (the single source of truth).

    python3 tools/codegen/gen.py           write the generated files
    python3 tools/codegen/gen.py --check   fail if any generated file is out of date
"""
import json
import math
import os
import sys
import tomllib
import zlib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
DEF = os.path.join(ROOT, "definitions", "ecu.toml")
OUT_TUNE_H = os.path.join(ROOT, "firmware", "src", "generated", "tune_def.h")
OUT_TUNE_C = os.path.join(ROOT, "firmware", "src", "generated", "tune_defaults.c")
OUT_RT_H = os.path.join(ROOT, "firmware", "src", "generated", "realtime.h")
OUT_INI = os.path.join(ROOT, "tuner", "e36ecu.ini")
OUT_JSON = os.path.join(ROOT, "tuner", "ecu_def.json")

TYPES = {  # name: (bytes, signed, C type)
    "U08": (1, False, "uint8_t"), "S08": (1, True, "int8_t"),
    "U16": (2, False, "uint16_t"), "S16": (2, True, "int16_t"),
    "U32": (4, False, "uint32_t"), "S32": (4, True, "int32_t"),
}
HEADER = "Generated by tools/codegen/gen.py from definitions/ecu.toml. Do not edit."


class DefError(Exception):
    pass


# --------------------------------------------------------------- defaults --

def interp(x, xs, ys):
    if x <= xs[0]:
        return ys[0]
    for i in range(1, len(xs)):
        if x <= xs[i]:
            f = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
            return ys[i - 1] + f * (ys[i] - ys[i - 1])
    return ys[-1]


def gen_table(kind, xs, ys):
    """Default 2D tables (values in shown units), indexed [y][x]."""
    out = []
    for y in ys:
        row = []
        for x in xs:
            if kind == "ve":            # x rpm, y tps: ITB-like, most change in the first 20 %
                rf = interp(x, [500, 2500, 4500, 7200], [0.80, 0.92, 1.00, 0.92])
                v = max(15.0, 95.0 * (1 - math.exp(-y / 10.0)) * rf)
            elif kind == "afr":         # x rpm, y load mg: rich at load, 14.7 cruise
                v = interp(y, [150, 250, 400, 480], [14.7, 14.7, 13.2, 12.6])
                if x < 1100 and y < 150:
                    v = 14.2
            elif kind == "ign":         # x rpm, y load mg: conservative (no knock control yet)
                light = interp(x, [500, 1000, 2000, 3000, 4000, 6000, 7200], [8, 12, 24, 30, 32, 34, 34])
                full = interp(x, [500, 1000, 2000, 3000, 4000, 5000, 6000, 7200], [5, 6, 12, 17, 21, 23, 25, 25])
                f = min(1.0, max(0.0, (y - 150) / 350.0))
                v = light + (full - light) * f
            elif kind == "eoi":         # x rpm, y load: closed-valve, moving earlier at high rpm
                v = interp(x, [800, 4000, 7200], [381, 381, 330])
            else:
                raise DefError(f"unknown default generator {kind!r}")
            row.append(v)
        out.append(row)
    return out


# ----------------------------------------------------------------- layout --

def field_count(f):
    n = 1
    for d in f.get("shape", [1]):
        n *= d
    return n


def to_raw(f, v):
    scale = f.get("scale", 1)
    translate = f.get("translate", 0)
    raw = round(v / scale - translate)
    size, signed, _ = TYPES[f["type"]]
    lo = -(1 << (8 * size - 1)) if signed else 0
    hi = (1 << (8 * size - 1)) - 1 if signed else (1 << (8 * size)) - 1
    if not lo <= raw <= hi:
        raise DefError(f"{f['name']}: default {v} -> raw {raw} does not fit {f['type']}")
    if "min" in f and "max" in f and not (f["min"] - 1e-9 <= v <= f["max"] + 1e-9):
        raise DefError(f"{f['name']}: default {v} outside [{f['min']}, {f['max']}]")
    return raw


def layout(d):
    names = set()
    fields = {}
    pages = []
    for p in d["pages"]:
        off = 0
        for f in p["fields"]:
            if f["name"] in names:
                raise DefError(f"duplicate name {f['name']}")
            if f["type"] not in TYPES:
                raise DefError(f"{f['name']}: bad type {f['type']}")
            names.add(f["name"])
            f["page"] = p["id"]
            f["offset"] = off
            f["size"] = TYPES[f["type"]][0] * field_count(f)
            off += f["size"]
            fields[f["name"]] = f
        p["size"] = off
        pages.append(p)

    # channels
    off = 0
    for c in d["channels"]:
        if c["name"] in names:
            raise DefError(f"duplicate name {c['name']}")
        names.add(c["name"])
        c["offset"] = off
        c["size"] = TYPES[c["type"]][0] * field_count(c)
        off += c["size"]
    d["rt_size"] = off

    # references from the UI sections
    for t in d.get("tables", []):
        for k in ("x", "y", "z"):
            if t[k] not in fields:
                raise DefError(f"table {t['name']}: unknown {k} field {t[k]}")
        z, x, y = fields[t["z"]], fields[t["x"]], fields[t["y"]]
        if z.get("shape") != [field_count(x), field_count(y)]:
            raise DefError(f"table {t['name']}: shape {z.get('shape')} vs axes {field_count(x)}x{field_count(y)}")
    for c in d.get("curves", []):
        for k in ("x", "y"):
            if c[k] not in fields:
                raise DefError(f"curve {c['name']}: unknown field {c[k]}")
        if field_count(fields[c["x"]]) != field_count(fields[c["y"]]):
            raise DefError(f"curve {c['name']}: axis lengths differ")
    for g in d.get("dialogs", []):
        for n in g["fields"]:
            if n not in fields:
                raise DefError(f"dialog {g['name']}: unknown field {n}")

    # defaults -> raw values
    for p in pages:
        for f in p["fields"]:
            n = field_count(f)
            dv = f["default"]
            if isinstance(dv, str):
                t = [x for x in d["tables"] if x["z"] == f["name"]][0]
                xs = [v for v in fields[t["x"]]["default"]]
                ys = [v for v in fields[t["y"]]["default"]]
                vals = [v for row in gen_table(dv, xs, ys) for v in row]
            elif isinstance(dv, list):
                vals = dv
            else:
                vals = [dv] * n
            if len(vals) != n:
                raise DefError(f"{f['name']}: {len(vals)} defaults for {n} values")
            f["raw_default"] = [to_raw(f, v) for v in vals]

    # layout hash: changes whenever any offset, type or size changes
    desc = ";".join(f"{f['page']}:{f['name']}:{f['type']}:{f['offset']}:{f['size']}"
                    for p in pages for f in p["fields"])
    d["layout_hash"] = zlib.crc32(desc.encode())
    return pages, fields


# --------------------------------------------------------------- C output --

def c_ident(name):
    out = ""
    for ch in name:
        out += ("_" + ch) if ch.isupper() else ch
    return out.upper()


def gen_tune_h(d, pages):
    L = [f"/* {HEADER} */",
         "#ifndef GENERATED_TUNE_DEF_H", "#define GENERATED_TUNE_DEF_H", "",
         "#include <stdint.h>", "",
         f'#define ECU_SIGNATURE    "{d["meta"]["signature"]}"',
         f'#define ECU_VERSION      "{d["meta"]["version"]}"', "",
         f"#define TUNE_PAGES       {len(pages)}u",
         f"#define TUNE_LAYOUT_HASH 0x{d['layout_hash']:08X}UL", ""]
    for p in pages:
        L.append(f"#define TUNE_PAGE{p['id']}_SIZE {p['size']}u   /* {p['name']} */")
    L.append("")
    for p in pages:
        L.append(f"extern uint8_t tune_page{p['id']}[TUNE_PAGE{p['id']}_SIZE];")
    L += ["",
          "/* Defaults (in flash on AVR): tune_default_page<N>[] in tune_defaults.c */",
          "#ifdef __AVR__", "#include <avr/pgmspace.h>", "#define TUNE_FLASH PROGMEM",
          "#define tune_flash_byte(p) pgm_read_byte(p)", "#else", "#define TUNE_FLASH",
          "#define tune_flash_byte(p) (*(p))", "#endif"]
    for p in pages:
        L.append(f"extern const uint8_t tune_default_page{p['id']}[TUNE_PAGE{p['id']}_SIZE] TUNE_FLASH;")
    L += ["",
          "static inline uint16_t tune_rd16(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }",
          "",
          "/* Raw accessors. Shown value = (raw + translate) * scale (TunerStudio convention). */"]
    for p in pages:
        L.append(f"\n/* ---- page {p['id']}: {p['name']} ---- */")
        buf = f"tune_page{p['id']}"
        for f in p["fields"]:
            name, off, typ = f["name"], f["offset"], f["type"]
            ident = c_ident(name)
            scale, tr = f.get("scale", 1), f.get("translate", 0)
            enc = f"shown = (raw {'+' if tr >= 0 else '-'} {abs(tr)}) * {scale}" if (scale != 1 or tr) else "shown = raw"
            unit = f.get("units", "")
            L.append(f"/* {name}: {typ}{f.get('shape', '')} {unit}, {enc} */")
            L.append(f"#define TU_{ident}_OFF {off}u")
            n = field_count(f)
            if "bits" in f:
                lo, hi = f["bits"]
                mask = (1 << (hi - lo + 1)) - 1
                L.append(f"static inline uint8_t tu_{name}(void) {{ return (uint8_t)(({buf}[{off}] >> {lo}) & {mask}u); }}")
            elif n == 1:
                if typ == "U08":
                    L.append(f"static inline uint8_t tu_{name}(void) {{ return {buf}[{off}]; }}")
                elif typ == "U16":
                    L.append(f"static inline uint16_t tu_{name}(void) {{ return tune_rd16(&{buf}[{off}]); }}")
                else:
                    raise DefError(f"{name}: scalar type {typ} not supported in C accessors")
            else:
                if len(f["shape"]) == 2:
                    L.append(f"#define TU_{ident}_X {f['shape'][0]}u")
                    L.append(f"#define TU_{ident}_Y {f['shape'][1]}u")
                else:
                    L.append(f"#define TU_{ident}_N {n}u")
                if typ == "U08":
                    L.append(f"static inline uint8_t tu_{name}(uint16_t i) {{ return {buf}[{off}u + i]; }}")
                    L.append(f"static inline const uint8_t *tu_{name}_ptr(void) {{ return &{buf}[{off}]; }}")
                elif typ == "U16":
                    L.append(f"static inline uint16_t tu_{name}(uint16_t i) {{ return tune_rd16(&{buf}[{off}u + 2u * i]); }}")
                    L.append(f"static inline const uint8_t *tu_{name}_ptr(void) {{ return &{buf}[{off}]; }}")
                else:
                    raise DefError(f"{name}: array type {typ} not supported in C accessors")
    L += ["", "#endif", ""]
    return "\n".join(L)


def gen_tune_c(pages):
    L = [f"/* {HEADER} */", '#include "generated/tune_def.h"', ""]
    for p in pages:
        raw = []
        for f in p["fields"]:
            size = TYPES[f["type"]][0]
            for v in f["raw_default"]:
                v &= (1 << (8 * size)) - 1
                raw += [(v >> (8 * k)) & 0xFF for k in range(size)]
        assert len(raw) == p["size"]
        L.append(f"const uint8_t tune_default_page{p['id']}[TUNE_PAGE{p['id']}_SIZE] TUNE_FLASH = {{")
        for i in range(0, len(raw), 16):
            L.append("    " + ", ".join(f"0x{b:02X}" for b in raw[i:i + 16]) + ",")
        L.append("};")
        L.append("")
    return "\n".join(L)


def gen_rt_h(d):
    L = [f"/* {HEADER} */",
         "#ifndef GENERATED_REALTIME_H", "#define GENERATED_REALTIME_H", "",
         "#include <stdint.h>", "",
         "/* Live data, sent to the tuner. Packed, little-endian. */",
         "typedef struct __attribute__((packed)) {"]
    for c in d["channels"]:
        ctype = TYPES[c["type"]][2]
        n = field_count(c)
        arr = f"[{n}]" if n > 1 else ""
        note = c.get("units", "")
        if c.get("scale", 1) != 1:
            note += f" x{c['scale']}"
        L.append(f"    {ctype + ' ' + c['name'] + arr + ';':<34}/* {c['offset']:3d} {note} */")
    L += ["} realtime_t;", "",
          f"#define REALTIME_SIZE {d['rt_size']}u",
          "_Static_assert(sizeof(realtime_t) == REALTIME_SIZE, \"realtime layout\");",
          "", "#endif", ""]
    return "\n".join(L)


# ------------------------------------------------------------ ini output --

def fmt_num(v):
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return str(v)


def ini_field(f):
    scale, tr = f.get("scale", 1), f.get("translate", 0)
    lo, hi = f.get("min", 0), f.get("max", 0)
    digits = f.get("digits", 0)
    units = f.get("units", "")
    if "bits" in f:
        opts = ", ".join(f'"{o}"' for o in f["options"])
        return f"{f['name']:<16}= bits,   {f['type']}, {f['offset']}, [{f['bits'][0]}:{f['bits'][1]}], {opts}"
    if "shape" not in f:
        return (f"{f['name']:<16}= scalar, {f['type']}, {f['offset']}, \"{units}\", {fmt_num(scale)}, "
                f"{fmt_num(tr)}, {fmt_num(lo)}, {fmt_num(hi)}, {digits}")
    shape = "x".join(str(s) for s in f["shape"])
    return (f"{f['name']:<16}= array,  {f['type']}, {f['offset']}, [{shape}], \"{units}\", {fmt_num(scale)}, "
            f"{fmt_num(tr)}, {fmt_num(lo)}, {fmt_num(hi)}, {digits}")


def label(name):
    out = ""
    for i, ch in enumerate(name):
        if ch.isupper() and i and not name[i - 1].isupper():
            out += " "
        out += ch
    return out[0].upper() + out[1:]


def gen_ini(d, pages, fields):
    np_ = len(pages)
    rep = lambda s: ", ".join([s] * np_)
    L = [f"; {HEADER}",
         "; TunerStudio project definition for the E36 M52 ECU.",
         "; NOT YET TESTED WITH TUNERSTUDIO ITSELF: if TunerStudio reports an error, note the line",
         "; and section so the generator can be fixed.", "",
         "[MegaTune]",
         "   MTversion      = 2.25",
         '   queryCommand   = "Q"',
         f'   signature      = "{d["meta"]["signature"]}"',
         '   versionInfo    = "S"', "",
         "[TunerStudio]",
         '   queryCommand   = "Q"',
         f'   signature      = "{d["meta"]["signature"]}"',
         '   versionInfo    = "S"', "",
         "[Constants]",
         "   endianness            = little",
         "   messageEnvelopeFormat = msEnvelope_1.0",
         f"   nPages                = {np_}",
         "   pageIdentifier        = " + ", ".join(f'"\\x{p["id"]:02x}\\x00"' for p in pages),
         "   pageSize              = " + ", ".join(str(p["size"]) for p in pages),
         '   pageReadCommand       = ' + rep('"R%2i%2o%2c"'),
         '   pageChunkWrite        = ' + rep('"M%2i%2o%2c%v"'),
         '   burnCommand           = ' + rep('"B%2i"'),
         "   blockingFactor        = 240",
         "   tableBlockingFactor   = 240",
         "   delayAfterPortOpen    = 2000",
         "   pageActivationDelay   = 10",
         "   interWriteDelay       = 5", ""]
    for i, p in enumerate(pages):
        L.append(f"page = {i + 1}   ; {p['name']}, {p['size']} bytes")
        for f in p["fields"]:
            L.append("   " + ini_field(f))
        L.append("")

    L += ["[SettingContextHelp]"]
    for p in pages:
        for f in p["fields"]:
            if "help" in f:
                L.append(f'   {f["name"]} = "{f["help"]}"')
    L.append("")

    L += ["[OutputChannels]",
          '   ochGetCommand  = "O%2o%2c"',
          f"   ochBlockSize   = {d['rt_size']}"]
    for c in d["channels"]:
        size = TYPES[c["type"]][0]
        names = c.get("names") or [c["name"]]
        for k, n in enumerate(names):
            L.append(f"   {n:<16}= scalar, {c['type']}, {c['offset'] + k * size}, \"{c.get('units', '')}\", "
                     f"{fmt_num(c.get('scale', 1))}, {fmt_num(c.get('translate', 0))}")
    L += ["   running         = bits, U08, " + str([c for c in d["channels"] if c["name"] == "engine"][0]["offset"]) + ", [0:0]",
          "   time            = { timeNow }", ""]

    L += ["[GaugeConfigurations]", '   gaugeCategory = "Engine"']
    for c in d["channels"]:
        if "gauge" in c:
            lo, hi, ld, lw, hw, hd = c["gauge"]
            dg = c.get("digits", 0)
            L.append(f'   {c["name"]}Gauge = {c["name"]}, "{label(c["name"])}", "{c.get("units", "")}", '
                     f"{fmt_num(lo)}, {fmt_num(hi)}, {fmt_num(ld)}, {fmt_num(lw)}, {fmt_num(hw)}, {fmt_num(hd)}, {dg}, {dg}")
    L.append("")

    gauges = [c["name"] + "Gauge" for c in d["channels"] if "gauge" in c][:8]
    L += ["[FrontPage]"]
    for i, g in enumerate(gauges):
        L.append(f"   gauge{i + 1} = {g}")
    L += ['   indicator = { sync == 3 }, "No full sync", "Full sync", white, black, green, black',
          '   indicator = { (engine & 2) }, "Not cranking", "Cranking", white, black, yellow, black',
          '   indicator = { (engine & 4) }, "Rev limit", "REV LIMIT", white, black, red, black',
          '   indicator = { (out_enable & 1) }, "Ign off", "Ign ON", white, black, red, black',
          '   indicator = { (out_enable & 2) }, "Inj off", "Inj ON", white, black, red, black',
          '   indicator = { (faults & 128) }, "Tune OK", "DEFAULT TUNE", white, black, yellow, black', ""]

    L += ["[Datalog]"]
    for c in d["channels"]:
        if c.get("log"):
            fmt = "float" if c.get("scale", 1) != 1 else "int"
            spec = f'"%.{c.get("digits", 1)}f"' if fmt == "float" else '"%d"'
            L.append(f'   entry = {c["name"]}, "{label(c["name"])}", {fmt}, {spec}')
    L.append("")

    L += ["[CurveEditor]"]
    for c in d.get("curves", []):
        fx, fy = fields[c["x"]], fields[c["y"]]
        L += [f'   curve = {c["name"]}, "{c["title"]}"',
              f'      columnLabel = "{label(c["x"])}", "{label(c["y"])}"',
              f'      xAxis       = {fmt_num(fx.get("min", 0))}, {fmt_num(fx.get("max", 100))}, 6',
              f'      yAxis       = {fmt_num(fy.get("min", 0))}, {fmt_num(fy.get("max", 100))}, 6',
              f'      xBins       = {c["x"]}',
              f'      yBins       = {c["y"]}',
              "      showTextValues = true"]
    L.append("")

    L += ["[TableEditor]"]
    for t in d.get("tables", []):
        page_index = [i for i, p in enumerate(pages) if p["id"] == fields[t["z"]]["page"]][0] + 1
        L += [f'   table = {t["name"]}, {t["name"]}Map, "{t["title"]}", {page_index}',
              f'      xBins       = {t["x"]}, {t["xchan"]}',
              f'      yBins       = {t["y"]}, {t["ychan"]}',
              f'      zBins       = {t["z"]}',
              "      gridHeight  = 2.0",
              "      gridOrient  = 250, 0, 340"]
    L.append("")

    L += ["[UserDefined]"]
    for g in d.get("dialogs", []):
        L.append(f'   dialog = {g["name"]}, "{g["title"]}"')
        for n in g["fields"]:
            units = fields[n].get("units", "")
            L.append(f'      field = "{label(n)}{" (" + units + ")" if units else ""}", {n}')
    L.append("")

    menus = {}
    for kind in ("dialogs", "tables", "curves"):
        for x in d.get(kind, []):
            menus.setdefault(x["menu"], []).append((x["name"], x["title"]))
    L += ["[Menu]", "   menuDialog = main"]
    for m, items in menus.items():
        L.append(f'   menu = "&{m}"')
        for n, t in items:
            L.append(f'      subMenu = {n}, "{t}"')
    L.append("")
    return "\n".join(L)


# ----------------------------------------------------------- JSON output --

def gen_json(d, pages):
    keep = ("name", "type", "offset", "size", "shape", "units", "scale", "translate", "min", "max",
            "digits", "bits", "options", "help")
    out = {
        "generated": HEADER,
        "signature": d["meta"]["signature"],
        "layout_hash": d["layout_hash"],
        "pages": [{"id": p["id"], "name": p["name"], "size": p["size"],
                   "fields": [{k: f[k] for k in keep if k in f} for f in p["fields"]]} for p in pages],
        "realtime_size": d["rt_size"],
        "channels": [{k: c[k] for k in ("name", "type", "offset", "shape", "names", "units", "scale",
                                        "translate", "digits") if k in c} for c in d["channels"]],
    }
    return json.dumps(out, indent=1) + "\n"


def build():
    with open(DEF, "rb") as fh:
        d = tomllib.load(fh)
    pages, fields = layout(d)
    return {
        OUT_TUNE_H: gen_tune_h(d, pages),
        OUT_TUNE_C: gen_tune_c(pages),
        OUT_RT_H: gen_rt_h(d),
        OUT_INI: gen_ini(d, pages, fields),
        OUT_JSON: gen_json(d, pages),
    }


def main(argv):
    try:
        outputs = build()
    except DefError as e:
        print("definition error:", e)
        return 1
    if "--check" in argv:
        stale = [p for p, text in outputs.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        for p in stale:
            print("out of date:", os.path.relpath(p, ROOT))
        if stale:
            print("run: python3 tools/codegen/gen.py")
        return 1 if stale else 0
    for p, text in outputs.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(text)
            print("wrote", os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
